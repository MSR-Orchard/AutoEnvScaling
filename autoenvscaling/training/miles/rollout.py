"""The Miles rollout function for `bridge` mode.

Wired in with ``--rollout-function-path autoenvscaling.training.miles.rollout.generate_rollout``
(see `config.MilesConfig`). For each rollout id Miles calls it with the engines awake and
serving the latest weights. It announces the router address through the bridge, waits for the
self-play loop's batch, and turns each RL sample row into a Miles `Sample`:

* the conversation is re-tokenized with Miles' `MultiTurnLossMaskGenerator` (the same chat
  template and loss mask its SFT path uses), so only assistant tokens carry loss;
* `reward` is r_S or r_P, and the precomputed advantage travels in `metadata["advantage"]`
  for `hooks.center_rewards_by_group`;
* no rollout log-probabilities are attached, so Miles computes the behaviour log-probabilities
  with the current actor. That is valid because the batch was generated by these same weights;
  the remaining gap is any difference between the re-rendered chat template and the exact
  tokens the engine produced.

A sample longer than the context limit is truncated and marked `remove_sample`, which zeroes its
loss mask while keeping it in the batch.

Requires the environment variable ``AES_BRIDGE_DIR`` (the bridge control directory) in the Ray
runtime environment. Only `generate_rollout` imports Miles.
"""

from __future__ import annotations

import logging
import os
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from autoenvscaling.training.miles import bridge

logger = logging.getLogger(__name__)

CONTROL_DIR_ENV = "AES_BRIDGE_DIR"
POLL_ENV = "AES_BRIDGE_POLL_S"

Encoder = Callable[[list[dict[str, Any]], list[dict[str, Any]] | None], tuple[list[int], list[int]]]


class OrchestratorFinished(RuntimeError):
    """The self-play loop wrote stop.json: there is nothing left to train on."""


def encode_rows(rows: Sequence[dict[str, Any]], encode: Encoder, max_tokens: int) -> list[dict[str, Any]]:
    """Tokenize sample rows. Pure: `encode(messages, tools) -> (token_ids, loss_mask)`.

    The response starts at the first token with loss; everything before it (system prompt,
    tools, the first user message) is the prompt.
    """
    out = []
    for row in rows:
        tokens, mask = encode(row["messages"], row.get("tools"))
        if len(tokens) != len(mask):
            raise ValueError(f"{row['trajectory_id']}: {len(tokens)} tokens but {len(mask)} mask entries")
        truncated = len(tokens) > max_tokens
        if truncated:
            tokens, mask = tokens[:max_tokens], mask[:max_tokens]
        start = mask.index(1) if 1 in mask else len(mask)
        remove = truncated or start >= len(tokens)
        out.append({"group_index": row["group_index"], "index": row["index"], "tokens": list(tokens),
                    "response_length": len(tokens) - start, "loss_mask": list(mask[start:]),
                    "reward": float(row["reward"]), "remove_sample": remove,
                    "prompt": list(row["messages"][:_first_assistant(row["messages"])]),
                    "label": row["group_id"],
                    "metadata": {**row.get("metadata", {}), "advantage": row["advantage"],
                                 "role": row["role"], "trajectory_id": row["trajectory_id"],
                                 "truncated": truncated}})
    return out


def _first_assistant(messages: Sequence[dict[str, Any]]) -> int:
    for i, m in enumerate(messages):
        if m.get("role") == "assistant":
            return i
    return len(messages)


def group_encoded(encoded: Sequence[dict[str, Any]]) -> list[list[dict[str, Any]]]:
    groups: dict[int, list[dict[str, Any]]] = {}
    for item in encoded:
        groups.setdefault(item["group_index"], []).append(item)
    return [groups[k] for k in sorted(groups)]


def batch_metrics(rows: Sequence[dict[str, Any]], encoded: Sequence[dict[str, Any]]) -> dict[str, float]:
    roles = {r["role"] for r in rows}
    rewards = [r["reward"] for r in rows]
    return {"aes/role_is_proposer": float(roles == {"proposer"}),
            "aes/groups": float(len({r["group_index"] for r in rows})),
            "aes/samples": float(len(rows)),
            "aes/mean_reward": sum(rewards) / len(rewards) if rewards else 0.0,
            "aes/removed_samples": float(sum(e["remove_sample"] for e in encoded))}


_ENCODER: Encoder | None = None


def _encoder(args: Any) -> Encoder:
    global _ENCODER
    if _ENCODER is None:
        from miles.utils.mask_utils import MultiTurnLossMaskGenerator
        from miles.utils.processing_utils import load_tokenizer

        tokenizer = load_tokenizer(args.hf_checkpoint,
                                   chat_template_path=getattr(args, "chat_template_path", None),
                                   trust_remote_code=True)
        generator = MultiTurnLossMaskGenerator(tokenizer, tokenizer_type=args.loss_mask_type)
        _ENCODER = lambda messages, tools: generator.get_loss_mask(messages, tools=tools)
    return _ENCODER


def generate_rollout(args: Any, rollout_id: int, data_source: Any, evaluation: bool = False):
    """Miles rollout-function entry point (legacy signature)."""
    if evaluation:
        raise NotImplementedError("bridge mode does not evaluate inside Miles; evaluate checkpoints separately")
    from miles.rollout.base_types import RolloutFnTrainOutput
    from miles.utils.types import Sample

    control_dir = Path(os.environ[CONTROL_DIR_ENV])
    router_url = f"http://{args.sglang_router_ip}:{args.sglang_router_port}"
    bridge.write_ready(control_dir, rollout_id, router_url)
    logger.info("rollout %d: waiting for the self-play loop in %s", rollout_id, control_dir)
    rows = bridge.wait_for_batch(control_dir, rollout_id, poll_s=float(os.environ.get(POLL_ENV, "5")))
    if rows is None:
        raise OrchestratorFinished(f"self-play loop stopped before rollout {rollout_id}")

    max_tokens = getattr(args, "rollout_max_context_len", None) or args.seq_length
    encoded = encode_rows(rows, _encoder(args), max_tokens)
    groups = []
    for members in group_encoded(encoded):
        group = []
        for item in members:
            sample = Sample(group_index=item["group_index"], index=item["index"], prompt=item["prompt"],
                            tokens=item["tokens"], response_length=item["response_length"],
                            loss_mask=item["loss_mask"], reward=item["reward"], label=item["label"],
                            remove_sample=item["remove_sample"], metadata=item["metadata"],
                            status=Sample.Status.COMPLETED)
            group.append(sample)
        groups.append(group)
    return RolloutFnTrainOutput(samples=groups, metrics=batch_metrics(rows, encoded))
